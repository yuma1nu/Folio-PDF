import { _electron as electron } from 'playwright';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const output = path.resolve('test-results'); await mkdir(output, { recursive: true });
const sample = path.join(output, 'drawing.pdf');
const pdf = await PDFDocument.create(); const font = await pdf.embedFont(StandardFonts.Helvetica);
for (let i = 0; i < 5; i++) {
  const page = pdf.addPage(i === 0 ? [2384, 3370] : [595, 842]);
  const h = page.getHeight();
  page.drawText(`FOLIO ENGINEERING / DRAWING ${i+1}`, { x: 45, y: h-80, size: 24, font, color: rgb(.2,.25,.28) });
  page.drawText(`SEARCH-TEST dimension ${i+1}`, { x: 45, y: h-110, size: 12, font });
  for (let j = 0; j < 200; j++) page.drawLine({ start: { x: 45+j*2, y: h-170 }, end: { x: 45+j*2, y: h-500 }, thickness: .3, color: rgb(.3,.35,.4) });
  page.drawRectangle({ x: 40, y: h-550, width: 470, height: 410, borderWidth: .4, borderColor: rgb(.1,.1,.1) });
}
await writeFile(sample, await pdf.save());
const env = { ...process.env, FOLIO_USER_DATA: path.join(output, `profile-${Date.now()}`) }; delete env.ELECTRON_RUN_AS_NODE;
const started = Date.now();
const app = await electron.launch({ args: ['.'], env });
const errors = [];
try {
  const page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  const poll = async (fn, timeout = 30000) => { const deadline = Date.now() + timeout; while (Date.now() < deadline) { if (await page.evaluate(fn)) return; await page.waitForTimeout(80); } throw new Error(`Timed out: ${fn}`); };
  page.on('console', msg => { if (msg.type() === 'error') console.log('BROWSER ERROR:', msg.text()); });
  await page.waitForSelector('.home');
  console.log('home-startup-ms', Date.now()-started);
  await page.screenshot({ path: path.join(output, 'home-light.png') });
  await page.evaluate(() => window.folio.settings({ theme: 'dark' }));
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.screenshot({ path: path.join(output, 'home-dark.png') });
  await page.evaluate(() => window.folio.settings({ theme: 'light' }));
  await page.evaluate(file => window.folio.open([file]), sample);
  await page.waitForSelector('.pdfViewer .page canvas', { timeout: 30000 });
  await page.waitForFunction(() => !!document.querySelector('.pdfViewer .page canvas')?.width);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: path.join(output, 'drawing-fit.png') });
  await page.getByRole('button', { name: '検索 (Ctrl+F)', exact: true }).click();
  await page.getByPlaceholder('検索する文字を入力').fill('SEARCH-TEST');
  await page.waitForFunction(() => document.querySelector('.search-count')?.textContent.includes('5件'), { timeout: 15000 });
  console.log('search OK');
  await page.getByRole('combobox', { name: '表示倍率' }).selectOption('1600');
  await page.waitForTimeout(1800);
  await page.screenshot({ path: path.join(output, 'drawing-1600.png') });
  console.log('canvases', await page.locator('.pdfViewer .page canvas').evaluateAll(nodes => nodes.map(n => ({ width: n.width, height: n.height, detail: n.className }))));
  await page.getByRole('combobox', { name: '表示倍率' }).selectOption('page-width');
  await page.getByRole('button', { name: 'ページ整理', exact: true }).click();
  await page.locator('.page-grid .thumbnail').nth(0).click();
  await page.getByRole('button', { name: '右に90度回転', exact: true }).click();
  await poll(async () => (await window.folio.snapshot()).docs[0].pages[0].rotation === 90);
  await page.getByRole('button', { name: '後ろへ移動', exact: true }).click();
  await poll(async () => (await window.folio.snapshot()).docs[0].pages[1].source === 0);
  await page.getByRole('button', { name: '選択ページを削除', exact: true }).click();
  await poll(async () => (await window.folio.snapshot()).docs[0].pages.length === 4);
  await page.getByRole('button', { name: '元に戻す', exact: true }).click();
  await poll(async () => (await window.folio.snapshot()).docs[0].pages.length === 5);
  await page.screenshot({ path: path.join(output, 'organize.png') });
  const editedPath = path.join(output, 'edited.pdf');
  await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }); dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false }); }, editedPath);
  await page.getByRole('button', { name: '名前を付けて保存 (Ctrl+S)', exact: true }).click();
  await poll(async () => (await window.folio.snapshot()).docs[0]?.name === 'edited.pdf');
  const edited = await PDFDocument.load(await readFile(editedPath));
  assert.equal(edited.getPageCount(), 5); assert.equal(edited.getPage(1).getRotation().angle, 90); assert.equal(edited.getPage(1).getWidth(), 2384);
  console.log('edit/save OK');
  const oldId = (await page.evaluate(() => window.folio.snapshot())).active;
  await page.evaluate(id => window.folio.move(id), oldId);
  await poll(async () => (await window.folio.snapshot()).docs.length === 0);
  const second = await app.waitForEvent('window', { timeout: 15000 }).catch(() => app.windows().find(w => w !== page));
  assert.ok(second); await second.waitForSelector('.pdfViewer .page canvas', { timeout: 30000 });
  console.log('window transfer OK');
  assert.deepEqual(errors, []);
  console.log('SMOKE PASS');
} finally { await app.evaluate(({ app }) => app.exit(0)); }
